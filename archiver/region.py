def continent_for(timezone: str) -> str:
    """Return the continent/box code ("us", "eu", "au") for an agency's timezone.

    Args:
        timezone: The agency's IANA timezone string, e.g. "America/Chicago".

    Raises:
        ValueError: If timezone is not present in TIMEZONE_TO_CONTINENT.
    """
    try:
        return TIMEZONE_TO_CONTINENT[timezone]
    except KeyError:
        raise ValueError(f"timezone {timezone!r} is not mapped to a continent")


def belongs_to_continent(timezone: str, continent: str) -> bool:
    """Return True if timezone belongs to the given continent/box code.

    Args:
        timezone: The agency's IANA timezone string.
        continent: The continent/box code to check against, e.g. "us".

    Raises:
        ValueError: If timezone is not present in TIMEZONE_TO_CONTINENT.
    """
    return continent_for(timezone) == continent
